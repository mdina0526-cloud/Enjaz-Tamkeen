using Microsoft.Extensions.Options;
using SalesSystem.Api.Infrastructure;

namespace SalesSystem.Api.Services;

/// <summary>
/// Stores uploads outside the web root under random names; files are only served through an authorized endpoint.
/// </summary>
public class FileStorage(IOptions<StorageOptions> options, IWebHostEnvironment env)
{
    private readonly StorageOptions _opt = options.Value;

    private string Root
    {
        get
        {
            var root = Path.IsPathRooted(_opt.UploadsPath) ? _opt.UploadsPath : Path.Combine(env.ContentRootPath, _opt.UploadsPath);
            Directory.CreateDirectory(root);
            return root;
        }
    }

    private static readonly Dictionary<string, (string ContentType, byte[][] Signatures)> Known = new()
    {
        [".pdf"] = ("application/pdf", [[0x25, 0x50, 0x44, 0x46]]),
        [".png"] = ("image/png", [[0x89, 0x50, 0x4E, 0x47]]),
        [".jpg"] = ("image/jpeg", [[0xFF, 0xD8, 0xFF]]),
        [".jpeg"] = ("image/jpeg", [[0xFF, 0xD8, 0xFF]]),
        [".webp"] = ("image/webp", [[0x52, 0x49, 0x46, 0x46]]),
    };

    public async Task<(string StoredName, string ContentType)> SaveAsync(IFormFile file, CancellationToken ct)
    {
        if (file.Length == 0) throw AppException.BadRequest("الملف المرفق فارغ");
        if (file.Length > _opt.MaxFileBytes) throw AppException.BadRequest($"حجم الملف يتجاوز الحد المسموح ({_opt.MaxFileBytes / 1024 / 1024} ميجابايت)");

        var ext = Path.GetExtension(file.FileName).ToLowerInvariant();
        if (!_opt.AllowedExtensions.Contains(ext) || !Known.TryGetValue(ext, out var info))
            throw AppException.BadRequest("نوع الملف غير مسموح. الأنواع المسموحة: PDF, JPG, PNG, WEBP");

        await using var input = file.OpenReadStream();
        var header = new byte[8];
        var read = await input.ReadAsync(header, ct);
        if (!info.Signatures.Any(sig => read >= sig.Length && header.AsSpan(0, sig.Length).SequenceEqual(sig)))
            throw AppException.BadRequest("محتوى الملف لا يطابق نوعه");
        input.Position = 0;

        var stored = $"{Guid.NewGuid():N}{ext}";
        await using var output = File.Create(Path.Combine(Root, stored));
        await input.CopyToAsync(output, ct);
        return (stored, info.ContentType);
    }

    public Stream? OpenRead(string storedName)
    {
        // Stored names are generated by us; reject anything that could escape the folder.
        if (storedName != Path.GetFileName(storedName)) return null;
        var path = Path.Combine(Root, storedName);
        return File.Exists(path) ? File.OpenRead(path) : null;
    }
}
